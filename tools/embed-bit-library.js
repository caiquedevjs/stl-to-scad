#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const root = path.join(__dirname, "..");
const source = path.join(root, "lib", "boardgame_insert_toolkit_lib.4.scad");
const target = path.join(root, "lib", "bit-library.embedded.js");
const compressed = zlib.gzipSync(fs.readFileSync(source), { level: 9 }).toString("base64");
const output = `// Generated by tools/embed-bit-library.js.\nwindow.BIT_LIBRARY_GZIP_BASE64 = "${compressed}";\n`;

fs.writeFileSync(target, output, "utf8");
console.log(`Embedded BIT library: ${target} (${compressed.length} base64 characters)`);
